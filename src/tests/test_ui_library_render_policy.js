const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");

const source = fs.readFileSync("app/ui/library_render_policy.js", "utf8");
const context = { globalThis: {}, Array, Number };
vm.runInNewContext(source, context);
const policy = context.globalThis.fnAudioLibraryRenderPolicy;
assert.equal(typeof policy.hasVisiblePresentation, "function");
assert.equal(typeof policy.shouldDeferListCommit, "function");
assert.deepEqual(policy.boundedRows([1, 2, 3], 2), [1, 2]);
assert.equal(policy.boundedRows(null).length, 0);
assert.equal(policy.boundedRows(Array.from({ length: 600 }, (_, index) => index)).length, 500);
assert.equal(policy.boundedRows([1, 2], Infinity).length, 2);
assert.equal(policy.boundedRows([1, 2], Symbol("bad")).length, 2);
assert.equal(policy.boundedRows({ filter() { throw new Error("must not call malformed response"); } }).length, 0);
assert.equal(policy.boundedTrackRows([{ id: "a" }, null, { id: "" }, { id: "b" }]).map(row => row.id).join(","), "a,b");
const sparseRows = Array.from({ length: 499 }, () => null);
sparseRows.push({ id: "after-malformed-prefix" });
assert.equal(policy.boundedTrackRows(sparseRows, 1).map(row => row.id).join(","), "after-malformed-prefix");
assert.equal(policy.boundedTrackRows(Array.from({ length: 501 }, (_, index) => ({ id: String(index) }))).length, 500);
assert.equal(policy.shouldDeferListCommit({ libraryLoading: true, hasVisiblePresentation: true, hasRenderedMarkup: true, listLength: 0 }), true);
assert.equal(policy.shouldDeferListCommit({ libraryLoading: true, hasVisiblePresentation: true, hasRenderedMarkup: true, listLength: 1 }), false);
assert.equal(policy.shouldDeferListCommit({ libraryLoading: false, hasVisiblePresentation: true, hasRenderedMarkup: true, listLength: 0 }), false);
assert.equal(policy.shouldDeferListCommit({ libraryLoading: true, hasVisiblePresentation: false, hasRenderedMarkup: true, listLength: 0 }), false);
assert.equal(policy.hasVisiblePresentation({ librarySnapshotHit: true }), true);
assert.equal(policy.hasVisiblePresentation({ pageItemsLength: 1 }), true);
assert.equal(policy.hasVisiblePresentation({ groupRowsLength: 2 }), true);
assert.equal(policy.hasVisiblePresentation({ folderRowsLength: 1 }), true);
assert.equal(policy.hasVisiblePresentation({ folderRootRowsLength: 1 }), true);
assert.equal(policy.hasVisiblePresentation({ libraryLoaded: 1 }), true);
assert.equal(policy.hasVisiblePresentation({ pageItemsLength: 0, groupRowsLength: 0 }), false);
const hostile = { valueOf() { throw new Error("must not coerce"); } };
assert.equal(policy.hasVisiblePresentation({ pageItemsLength: hostile }), false);
assert.equal(policy.hasVisiblePresentation({ pageItemsLength: "1" }), false);
console.log("Library render policy regression checks passed.");
