const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");

const source = fs.readFileSync("app/ui/album_metadata_cache.js", "utf8");
const context = { globalThis: {}, Map };
vm.runInNewContext(source, context);
const cache = context.globalThis.fnAudioAlbumMetadataCache(3);
cache.set("a", { artist: "A" }).set("b", { artist: "B" }).set("c", { artist: "C" });
assert.equal(cache.size, 3);
cache.get("a");
cache.set("d", { artist: "D" });
assert.equal(cache.has("a"), true);
assert.equal(cache.has("b"), false);
assert.equal(cache.get("a").artist, "A");
assert.equal(cache.limit, 3);
cache.set("", { artist: "ignored" });
assert.equal(cache.size, 3);
cache.set("bad", "ignored");
assert.equal(cache.has("bad"), false);
cache.set("bounded", { artist: "x".repeat(5000), image_url: "y".repeat(9000) });
assert.equal(cache.get("bounded").artist.length, 1024);
assert.equal(cache.get("bounded").image_url.length, 4096);
const hostile = { toString() { throw new Error("must not escape"); } };
assert.equal(cache.get(hostile), undefined);
const collidingObject = { toString() { return "a"; } };
assert.equal(cache.get(collidingObject), undefined, "object keys must not coerce into cached string keys");
assert.equal(cache.set(collidingObject, { artist: "ignored" }).size, 3);
console.log("Album metadata cache regression checks passed.");
