const fs = require("fs");
const vm = require("vm");
const source = fs.readFileSync(require("path").join(__dirname, "..", "app", "ui", "creator_view_policy.js"), "utf8");
const context = { globalThis: {} };
vm.runInNewContext(source, context);
const policy = context.globalThis.fnAudioCreatorViewPolicy;
if (!policy) throw new Error("creator view policy was not exported");

const state = { view: "artists", groupName: "", artistName: "", artistAllTracks: false, artistTrackTotal: 0 };
if (!policy.isCreatorView("artists") || policy.isCreatorView("albums")) throw new Error("creator view detection failed");
policy.setCurrentCreator(state, "A", "3");
if (policy.currentCreatorName(state) !== "A" || policy.currentCreatorTrackTotal(state) !== 3) throw new Error("creator mutation failed");
policy.setCurrentCreator(state, { toString() { throw new Error("must not stringify"); } }, 3);
if (policy.currentCreatorName(state) !== "") throw new Error("creator names must reject arbitrary objects");
policy.setCurrentCreator(state, "  A  ", 3);
if (policy.currentCreatorName(state) !== "A") throw new Error("creator names must be normalized");
policy.setCurrentCreator(state, "A", true);
if (policy.currentCreatorTrackTotal(state) !== 0) throw new Error("boolean creator totals must be rejected");
policy.setCurrentCreator(state, "A", Infinity);
if (policy.currentCreatorTrackTotal(state) !== 0) throw new Error("non-finite creator totals must be rejected");
policy.setCurrentCreator(state, "A", "1000000001");
if (policy.currentCreatorTrackTotal(state) !== 1000000000) throw new Error("creator totals must be bounded");
if (policy.boundedTrackTotal({ valueOf() { throw new Error("must not coerce"); } }) !== 0) throw new Error("arbitrary totals must not be coerced");
policy.setCurrentCreatorAllTracks(state, "true");
if (policy.currentCreatorAllTracks(state)) throw new Error("creator all-tracks state must require a JSON boolean");
policy.setCurrentCreatorAllTracks(state, true);
if (!policy.currentCreatorAllTracks(state)) throw new Error("creator all-tracks state must preserve true");
const hostileState = new Proxy({}, { get() { throw new Error("broken state"); } });
if (policy.currentCreatorName(hostileState) !== "" || policy.currentCreatorAllTracks(hostileState)) throw new Error("broken creator state must use safe defaults");
policy.setCurrentCreatorAllTracks(state, false);
if (!policy.isCreatorAlbumView(state)) throw new Error("creator album view failed");
policy.setCurrentCreatorAllTracks(state, true);
if (!policy.isCreatorAllTracksView(state)) throw new Error("all tracks view failed");
policy.resetCreatorState(state);
if (policy.currentCreatorName(state) !== "") throw new Error("creator reset failed");
console.log("Creator view policy regression checks passed.");
