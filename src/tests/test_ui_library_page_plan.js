const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync("app/ui/library_page_plan.js", "utf8");
const context = { globalThis: {} };
vm.runInNewContext(source, context);
const plan = context.globalThis.fnAudioLibraryPagePlan;
assert.deepEqual(Array.from(plan.remainingPageOffsets(0, 120, 0)), []);
assert.deepEqual(Array.from(plan.remainingPageOffsets(100, 120, 100)), []);
assert.deepEqual(Array.from(plan.remainingPageOffsets(250, 100, 100)), [100, 200]);
assert.deepEqual(Array.from(plan.remainingPageOffsets("250", "100", "100")), [100, 200]);
const normalized = plan.remainingPageOffsets(250, 0, 100);
assert.equal(normalized.length, 249);
assert.equal(normalized[0], 1);
assert.equal(normalized.at(-1), 249);
assert.equal(plan.remainingPageOffsets(1200, 0.5, 500).length, 1199);
assert.equal(plan.remainingPageOffsets(1200, 0.5, 500)[0], 1);
assert.equal(plan.remainingPageOffsets(1200, 0.5, 500).at(-1), 1199);
assert.deepEqual(Array.from(plan.remainingPageOffsets(1200, 9999, 1)), [500, 1000]);
assert.deepEqual(Array.from(plan.remainingPageOffsets(1000000, 100, 100, 200000)), Array.from({ length: 1999 }, (_, index) => (index + 1) * 100));
assert.deepEqual(Array.from(plan.remainingPageOffsets(1000000, 100, 100, 250)), [100, 200]);
assert.deepEqual(Array.from(plan.remainingPageOffsets(Infinity, 100, 1)), []);
assert.deepEqual(Array.from(plan.remainingPageOffsets(Symbol("bad"), 100, 1)), []);
assert.deepEqual(Array.from(plan.remainingPageOffsets("9".repeat(1000), 100, 1)), []);
assert.deepEqual(Array.from(plan.remainingPageOffsets({ valueOf() { throw new Error("must not coerce"); } }, 100, 1)), []);
const bounded = plan.remainingPageOffsets(1000000, 1, 1);
assert.equal(bounded.length, 8192);
assert.equal(bounded.at(-1), 8192);
const batches = [...plan.pageOffsetBatches(1000, 100, 100, 1000, 2)].map(batch => Array.from(batch));
assert.deepEqual(batches, [[100, 200], [300, 400], [500, 600], [700, 800], [900]]);
assert.equal([...plan.pageOffsetBatches(1000000, 1, 1, 200000, 32)].length, 256);
assert.equal([...plan.pageOffsetBatches(1000000, 1, 1, 200000, 32)][0].length, 32);
assert.deepEqual([...plan.pageOffsetBatches(Symbol("bad"), 100, 1)], []);
assert.match(source, /MAX_PAGE_OFFSETS = 8192/);
assert.match(source, /MAX_NUMERIC_TEXT = 64/);
assert.match(source, /function pageOffsetBatches/);
console.log("Library page plan regression checks passed.");
