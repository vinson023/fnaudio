const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");

const source = fs.readFileSync("app/ui/item_cache.js", "utf8");
const context = { globalThis: {}, Map, Set };
vm.runInNewContext(source, context);
const cache = context.globalThis.fnAudioItemCache(1000);
assert.doesNotThrow(() => cache.set({ toString() { throw new Error("must not stringify"); } }, 1));
assert.equal(cache.has({}), false);
assert.equal(cache.set("x".repeat(4097), 1).size, 0);
cache.set("old", 1).set("protected", 2);
assert.equal(cache.get("old"), 1);
for (let index = 0; index < 1001; index += 1) cache.set(`item-${index}`, index);
cache.trim(new Set(["protected"]));
assert.equal(cache.has("protected"), true);
assert.equal(cache.size, 1000);
const protectedCache = context.globalThis.fnAudioItemCache(1000);
protectedCache.set("queue-track", 1);
for (let index = 0; index < 1000; index += 1) protectedCache.set(`new-${index}`, index);
protectedCache.trim(new Set(["queue-track"]));
assert.equal(protectedCache.has("queue-track"), true);
const manyProtected = context.globalThis.fnAudioItemCache(1000);
manyProtected.set("protected-a", 1).set("protected-b", 2);
for (let index = 0; index < 1005; index += 1) manyProtected.set(`bulk-${index}`, index);
manyProtected.trim(new Set(["protected-a", "protected-b"]));
assert.equal(manyProtected.size, 1000);
assert.equal(manyProtected.has("protected-a"), true);
assert.equal(manyProtected.has("protected-b"), true);
cache.clear();
assert.equal(cache.size, 0);
const bounded = context.globalThis.fnAudioItemCache(Infinity);
for (let index = 0; index < 12001; index += 1) bounded.set(`bounded-${index}`, index);
bounded.trim();
assert.equal(bounded.size, 12000);
const malformed = context.globalThis.fnAudioItemCache(Symbol("bad"));
for (let index = 0; index < 1001; index += 1) malformed.set(`malformed-${index}`, index);
malformed.trim();
assert.equal(malformed.size, 1001);
const capped = context.globalThis.fnAudioItemCache(Number.MAX_SAFE_INTEGER);
for (let index = 0; index < 50001; index += 1) capped.set(`capped-${index}`, index);
capped.trim();
assert.equal(capped.size, 50000);
console.log("Item cache regression checks passed.");
