const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const source = fs.readFileSync(path.join(__dirname, "..", "app", "ui", "metadata_response_policy.js"), "utf8");
const sandbox = { globalThis: {} };
vm.runInNewContext(source, sandbox);
const unwrap = sandbox.globalThis.fnAudioMetadataResponsePolicy.unwrap;
const unwrapTransport = sandbox.globalThis.fnAudioMetadataResponsePolicy.unwrapTransport;
const same = (actual, expected) => assert.equal(JSON.stringify(actual), JSON.stringify(expected));
same(unwrap({ status: "auto" }), { status: "auto" });
same(unwrap({ data: { status: "pending" } }), { status: "pending" });
same(unwrap({ data: { data: { status: "failed" } } }), { status: "failed" });
same(unwrap({ data: { data: { data: { status: "third-envelope" } } } }), { status: "third-envelope" });
same(unwrap({ data: { data: { data: { data: { status: "fourth-envelope" } } } } }), { status: "fourth-envelope" });
same(unwrap({ data: { data: { data: { data: { data: { status: "too-deep" } } } } } }), { data: { status: "too-deep" } });
same(unwrap({ data: { data: { data: { data: { status: "app-fourth-envelope" } } } } }, 4), { status: "app-fourth-envelope" });
same(unwrap({ data: { data: { data: { data: { data: { status: "app-too-deep" } } } } } }, 4), { data: { status: "app-too-deep" } });
same(unwrap({ result: { payload: { metadata: { status: "bridge-envelope" } } } }), { status: "bridge-envelope" });
same(unwrap({ ok: "false", data: { status: "pending" } }), { ok: false });
same(unwrap({ ok: "false", status: "pending" }), { ok: false });
same(unwrap({ status: "pending", metadata: { title: "must-not-unwrap" } }), { status: "pending", metadata: { title: "must-not-unwrap" } });
same(unwrap(null), {});
same(unwrap({ data: [] }), { data: [] });
same(unwrapTransport({ scanning: false, count: 3 }), { scanning: false, count: 3 });
same(unwrapTransport({ data: { scanning: false, count: 3 } }), { scanning: false, count: 3 });
same(unwrapTransport({ result: { payload: { scanning: true } } }), { scanning: true });
same(unwrapTransport({ data: { data: { data: { data: { data: { scanning: true } } } } } }), { data: { scanning: true } });
same(unwrapTransport(null), {});
assert.equal(unwrap({ status: "no_match" }).status, "no_match");
const brokenEnvelope = {};
Object.defineProperty(brokenEnvelope, "data", { get() { throw new Error("bridge getter"); } });
assert.deepEqual(unwrap(brokenEnvelope), brokenEnvelope, "Broken envelope getters must not abort metadata recovery");
const mixedEnvelope = { result: { status: "pending" } };
Object.defineProperty(mixedEnvelope, "data", { get() { throw new Error("bridge getter"); } });
same(unwrap(mixedEnvelope), { status: "pending" });
const recoverable = sandbox.globalThis.fnAudioMetadataResponsePolicy.isRecoverableFilenameFallback;
assert.equal(recoverable({ status: "NO_MATCH" }, { source: "filename" }), true);
assert.equal(recoverable({ status: { toString() { throw new Error("coercion"); } } }, { source: "filename" }), false);
assert.equal(recoverable({ status: "failed" }, { source: { toString() { throw new Error("coercion"); } } }), false);
const transient = sandbox.globalThis.fnAudioMetadataResponsePolicy.isTransientHttpStatus;
assert.equal(transient(408), true);
assert.equal(transient(425), true);
assert.equal(transient(429), true);
assert.equal(transient(500), true);
assert.equal(transient(400), false);
assert.equal(transient("429"), false);
console.log("Metadata response policy regression checks passed.");
